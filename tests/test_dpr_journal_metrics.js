const assert = require('node:assert/strict');
const api = require('../app/dpr-journal-metrics.js');
const data = {status:'ready', generated_at:'2026-10-22T00:00:00Z', papers:{'2610.25628':{kind:'preprint',venue:'Journal'}, j:{kind:'journal',venue:'Journal',issns:['1234-567X']}}, metrics:[{journal:'Journal',issn:'1234-567X',kind:'中科院升级版',value:'1区',category:'计算机科学',year:null},{journal:'Journal',kind:'JIF',value:'11.1',year:null}]};
assert.equal(api.paperID('#/a/2610.25628v1-paper'), '2610.25628');
assert.equal(api.applicable(data, '2610.25628').length, 0);
assert.equal(api.applicable(data, 'j').length, 2);
assert.ok(api.render(data,'j').includes('接口未提供数据年份'));
assert.ok(!api.render(data,'2610.25628').includes('11.1'));
assert.ok(!api.render(data,'2610.25628').includes('待核实'));
data.papers.conference={kind:'conference',venue:'NeurIPS 2026',note:'arXiv author acceptance statement'};
assert.ok(api.render(data,'conference').includes('不适用'));
assert.ok(!api.render(data,'conference').includes('dpr-journal-tile'));
const evil = JSON.parse(JSON.stringify(data)); evil.papers.j.venue = '<img onerror=alert(1)>';
assert.ok(!api.render(evil,'j').includes('<img'));
evil.papers.j.venue='Journal'; evil.papers.j.issns=['9999-9999'];
assert.equal(api.applicable(evil,'j').length,1); // only title-only record can match
console.log('PASS: correct paper identity, preprint/ISSN boundaries, unknown years, escaped provider text');
data.citations={'2610.25628':{count:0,status:'confirmed',provider:'OpenAlex',scope:'arXiv 版本',checkedAt:'2026-10-23T00:00:00Z',source:'https://openalex.org/W123'}};
assert.ok(api.render(data,'2610.25628').includes('被引 0'));
assert.ok(api.render(data,'2610.25628').includes('OpenAlex'));
assert.ok(api.render(data,'2610.25628').includes('dpr-chip-cited'));
data.citations['2610.25628']={count:null,status:'unindexed',provider:'OpenAlex'};
assert.ok(api.render(data,'2610.25628').includes('尚未收录'));
assert.ok(!api.render(data,'2610.25628').includes('被引 0'));
assert.ok(api.render(data,'j').includes('dpr-chip-cas'));
assert.ok(api.render(data,'j').includes('dpr-chip-if'));
console.log('PASS: colored metric pills, confirmed zero distinct from unknown, citation provenance');
const journalKey='journal-678a878edcdc94c01adf';
assert.equal(api.paperID('#/journal-library/' + journalKey, 'https://arxiv.org/pdf/2601.12345'), journalKey);
data.papers[journalKey]=data.papers.j;
const cards=api.catalog(data,{papers:[{paper_id:journalKey,route:'journal-library/'+journalKey,title:'A <journal> paper',evidence:'Source abstract'}]});
assert.ok(cards.includes('IF 11.1') && cards.includes('中科院升级版'));
assert.ok(cards.includes('A &lt;journal&gt; paper') && !cards.includes('id="dpr-journal-metrics"'));
assert.equal(api.catalog(data,{papers:[{route:'javascript:bad'}]}),'');
console.log('PASS: journal identity takes precedence over an arXiv OA copy; real route catalog and metric association');
